// ---------------------------------------------------------------- 補助

function kebab(name) {
	return name
		.replace(/<.*>/, '')
		.replace(/([a-z0-9])([A-Z])/g, '$1-$2')
		.replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2')
		.toLowerCase();
}

// Unity の ObjectNames.NicifyVariableName に合わせる（m_ と _ と k の接頭辞を外し、単語を分ける）。
function nicify(name) {
	let n = name.replace(/^m_/, '').replace(/^_/, '').replace(/^k([A-Z])/, '$1');
	n = n.replace(/([a-z0-9])([A-Z])/g, '$1 $2').replace(/([A-Z]+)([A-Z][a-z])/g, '$1 $2');
	return n.charAt(0).toUpperCase() + n.slice(1);
}

// 同じ型の中で名前が重なるメンバーだけ、引数の型で区別する。
function assignIds(members) {
	const counts = new Map();
	for (const m of members) counts.set(m.name, (counts.get(m.name) ?? 0) + 1);
	for (const m of members) {
		m.id = counts.get(m.name) > 1 && m.parameters ? `${m.name}(${m.parameters.join(', ')})` : m.name;
	}
	const seen = new Set();
	for (const m of members) {
		if (seen.has(m.id)) m.id = `${m.id}#${m.line}`;
		seen.add(m.id);
	}
}

function sectionOf(m) {
	switch (m.kind) {
		case 'field':
			return m.isStatic ? 'staticField' : 'field';
		case 'property':
			return m.isStatic ? 'staticProperty' : 'property';
		case 'method':
			return m.isStatic ? 'staticMethod' : 'method';
		default:
			return m.kind;
	}
}

function attr(t, name) {
	return t.attributes.find((a) => a.name === name);
}

function unquote(s) {
	const m = /^"(.*)"$/.exec((s ?? '').trim());
	return m ? m[1] : s;
}

function escapeCell(s) {
	return String(s ?? '').replace(/\|/g, '\\|').replace(/\n+/g, ' ');
}

function code(s) {
	if (s == null || s === '') return '';
	const text = String(s);
	const fence = text.includes('`') ? '`` ' : '`';
	return `${fence}${text}${fence === '`' ? '`' : ' ``'}`;
}

// 説明文: frontmatter の description、冒頭の本文、<!-- members --> 以降の「### id」ごとの説明。
function readNotes(lang, id) {
	const file = path.join(notesDir, lang, `${id}.md`);
	if (!fs.existsSync(file)) return null;
	let text = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
	let description = '';
	const fm = /^---\n([\s\S]*?)\n---\n/.exec(text);
	if (fm) {
		description = parseYaml(fm[1])?.description ?? '';
		text = text.slice(fm[0].length);
	}
	const [intro, membersPart = ''] = text.split(MEMBERS_MARKER);
	const members = new Map();
	const re = /^### (.+)$/gm;
	const heads = [...membersPart.matchAll(re)];
	heads.forEach((h, i) => {
		const start = h.index + h[0].length;
		const end = i + 1 < heads.length ? heads[i + 1].index : membersPart.length;
		const body = membersPart
			.slice(start, end)
			.replace(/<!--[\s\S]*?-->/g, '')
			.trim();
		members.set(h[1].trim(), body);
	});
	return { file, description, intro: intro.replace(/<!--[\s\S]*?-->/g, '').trim(), members };
}

function writeScaffold(lang, id, description, intro, entries) {
	const file = path.join(notesDir, lang, `${id}.md`);
	if (fs.existsSync(file)) return;
	fs.mkdirSync(path.dirname(file), { recursive: true });
	const lines = ['---', `description: ${JSON.stringify(description ?? '')}`, '---', '', intro ?? '', '', MEMBERS_MARKER, ''];
	for (const e of entries) {
		lines.push(`### ${e.id}`, '');
		if (e.draft && lang === 'ja') lines.push(`<!-- draft: ${e.draft.replace(/-->/g, '--&gt;')} -->`, '');
	}
	fs.writeFileSync(file, lines.join('\n'));
}

// ---------------------------------------------------------------- 型のページ

function renderTypePage(lang, category, entry, type, members, notes) {
	const t = T[lang];
	const out = [];
	const title = entry.title ?? type.name;
	const description = notes?.description || '';
	out.push('---', `title: ${JSON.stringify(title)}`);
	if (description) out.push(`description: ${JSON.stringify(description)}`);
	out.push('editUrl: false', '---', '', GENERATED_MARKER, '');

	const meta = [
		[t.namespace, code(type.namespace)],
		[t.assembly, code(type.assembly)],
		[t.source, type.files.map((f) => code(f.file)).join('、')],
	];
	const addComponent = attr(type, 'AddComponentMenu');
	if (addComponent && unquote(addComponent.arguments?.split(',')[0]))
		meta.push([t.addComponent, code(unquote(addComponent.arguments.split(',')[0]))]);
	const createAsset = attr(type, 'CreateAssetMenu');
	if (createAsset) {
		const menu = /menuName\s*=\s*"([^"]+)"/.exec(createAsset.arguments ?? '');
		if (menu) meta.push([t.createAsset, code(`Assets/Create/${menu[1]}`)]);
	}
	const shownAttrs = type.attributes
		.filter((a) => !['AddComponentMenu', 'CreateAssetMenu', 'MovedFrom', 'HelpURL'].includes(a.name))
		.map((a) => code(`[${a.name}${a.arguments ? `(${a.arguments})` : ''}]`));
	if (shownAttrs.length) meta.push([t.attributes, shownAttrs.join(' ')]);
	out.push('| | |', '| --- | --- |', ...meta.map(([k, v]) => `| ${k} | ${v} |`), '');
	out.push('```csharp', type.signature, '```', '');
	if (notes?.intro) out.push(notes.intro, '');

	const describe = (m) => {
		const text = notes?.members.get(m.id);
		if (text) return text;
		const autoKey = m.kind === 'operator' ? m.name : m.name.replace(/\(.*$/, '');
		if (t.auto[autoKey]) return t.auto[autoKey];
		return null;
	};

	const inspector = members.filter((m) => m.serialized && !m.attributes.some((a) => a.name === 'HideInInspector'));
	if (inspector.length) {
		out.push(`## ${t.inspector}`, '');
		// 表は列が多いと狭い画面ではみ出すので、項目ごとの箇条書きにする。
		for (const m of inspector) {
			const range = m.attributes.find((a) => a.name === 'Range');
			const facts = [code(m.name), code(m.type)];
			if (range) facts.push(`${t.range} ${range.arguments.replace(/(\d)f\b/g, '$1').replace(/\s*,\s*/, '–')}`);
			if (m.defaultValue) facts.push(`${t.default} ${code(m.defaultValue)}`);
			// 箇条書きの中に収めるため、2 行目以降を字下げする。
			const desc = (describe(m) ?? t.noDescription).replace(/\n/g, '\n  ');
			out.push(`- **${nicify(m.name)}**（${facts.join(t.sep)}）  `, `  ${desc}`);
		}
		out.push('');
	}

	const rest = members.filter((m) => !inspector.includes(m));
	const bySection = new Map();
	for (const m of rest) {
		const s = sectionOf(m);
		if (!bySection.has(s)) bySection.set(s, []);
		bySection.get(s).push(m);
	}
	for (const s of SECTION_ORDER) {
		const list = bySection.get(s);
		if (!list?.length) continue;
		out.push(`## ${t.sections[s]}`, '');
		if (s === 'enumMember') {
			out.push(`| ${lang === 'ja' ? '名前' : 'Name'} | ${lang === 'ja' ? '値' : 'Value'} | ${lang === 'ja' ? '説明' : 'Description'} |`, '| --- | --- | --- |');
			for (const m of list) out.push(`| ${code(m.name)} | ${code(m.defaultValue ?? '')} | ${escapeCell(describe(m) ?? t.noDescription)} |`);
			out.push('');
			continue;
		}
		// 同じ名前のオーバーロードは 1 つの見出しにまとめる。
		const groups = new Map();
		for (const m of list) {
			if (!groups.has(m.name)) groups.set(m.name, []);
			groups.get(m.name).push(m);
		}
		for (const [name, overloads] of groups) {
			out.push(`### ${name}`, '');
			for (const m of overloads) {
				out.push('```csharp', m.signature + (m.kind === 'field' && m.defaultValue ? ` = ${m.defaultValue}` : ''), '```', '');
				out.push(describe(m) ?? t.noDescription, '');
			}
		}
	}
	out.push('---', '', `<small>${t.generatedFrom(api.source)}</small>`, '');
	return out.join('\n');
}

// ---------------------------------------------------------------- Shader のページ

function renderHlslPage(lang, page, notes, items) {
	const t = T[lang];
	const out = ['---', `title: ${JSON.stringify(page.title[lang])}`];
	if (notes?.description) out.push(`description: ${JSON.stringify(notes.description)}`);
	out.push('editUrl: false', '---', '', GENERATED_MARKER, '');
	if (notes?.intro) out.push(notes.intro, '');
	if (page.kind === 'hlsl-functions') {
		for (const f of items) {
			out.push(`## ${f.name}`, '', `${t.source}: ${code(`${f.file}:${f.line}`)}`, '');
			for (const sig of f.signatures) out.push('```hlsl', sig, '```', '');
			out.push(notes?.members.get(f.name) || t.noDescription, '');
		}
	} else if (page.kind === 'hlsl-includes') {
		for (const i of items) {
			out.push(`## ${i.name}`, '', code(i.file), '');
			out.push(notes?.members.get(i.name) || t.noDescription, '');
		}
	} else {
		out.push(`| ${t.identifiers} | ${t.source} | ${lang === 'ja' ? '説明' : 'Description'} |`, '| --- | --- | --- |');
		for (const i of items)
			out.push(`| ${code(i.name)} | ${code(`${i.file}:${i.line}`)} | ${escapeCell(notes?.members.get(i.name) || t.noDescription)} |`);
		out.push('');
	}
	out.push('---', '', `<small>${t.generatedFrom(api.source)}</small>`, '');
	return out.join('\n');
}

// ---------------------------------------------------------------- 本体

const pages = []; // { lang, rel, content }
const usedNotes = new Set();

for (const category of allowlist.categories) {
	for (const entry of category.types ?? []) {
		const type = typesByName.get(entry.type);
		if (!type) {
			errors.push(`allowlist: type not found in Omni source: ${entry.type} (removed or renamed?)`);
			continue;
		}
		const members = type.members.map((m) => ({ ...m }));
		assignIds(members);
		for (const ex of entry.exclude ?? []) {
			if (!members.some((m) => m.id === ex))
				errors.push(`allowlist: excluded member not found: ${entry.type} :: ${ex}`);
		}
		// 載せるのは列挙型の値、公開メンバー、Inspector に出る保存フィールド（[HideInInspector] を除く）。
		const kept = members.filter(
			(m) =>
				!(entry.exclude ?? []).includes(m.id) &&
				(m.kind === 'enumMember' ||
					m.isPublic ||
					(m.serialized && !m.attributes.some((a) => a.name === 'HideInInspector'))),
		);
		const id = entry.type;
		const slug = entry.slug ?? kebab(type.name);
		for (const lang of langs) {
			if (scaffold)
				writeScaffold(lang, id, lang === 'ja' ? firstSentence(type.summary) : '', '', kept.map((m) => ({ id: m.id, draft: m.summary })));
			const notes = readNotes(lang, id);
			usedNotes.add(`${lang}/${id}.md`);
			if (!notes) warnings.push(`notes missing: ${lang}/${id}.md`);
			else {
				for (const key of notes.members.keys())
					if (!kept.some((m) => m.id === key))
						errors.push(`notes: ${lang}/${id}.md describes a member that does not exist: ${key}`);
				if (!notes.description) warnings.push(`notes: ${lang}/${id}.md has no description`);
			}
			for (const m of kept) {
				const has = notes?.members.get(m.id) || T[lang].auto[m.kind === 'operator' ? m.name : m.name.replace(/\(.*$/, '')];
				if (!has) warnings.push(`undocumented: ${lang} ${id} :: ${m.id}`);
			}
			pages.push({
				lang,
				rel: `${category.id}/${slug}.md`,
				content: renderTypePage(lang, category, entry, type, kept, notes),
			});
		}
	}

	for (const page of category.pages ?? []) {
		let items = [];
		if (page.kind === 'hlsl-functions') {
			for (const name of page.functions) {
				// Shader Graph の Custom Function は、名前に _float／_half を付けた 2 つの版を持つ。
				const found = api.hlsl.functions.filter(
					(f) => [name, `${name}_float`, `${name}_half`].includes(f.name) && (!page.file || f.file === page.file),
				);
				if (!found.length) {
					errors.push(`allowlist: HLSL function not found: ${name}`);
					continue;
				}
				const signatures = [...new Set(found.map((f) => `${f.returnType} ${f.name}(${f.parameters})`))];
				items.push({ name, file: found[0].file, line: found[0].line, signatures });
			}
		} else if (page.kind === 'hlsl-includes') {
			for (const name of page.includes) {
				const file = api.hlsl.includes.find((f) => f.endsWith(`/${name}`));
				if (!file) {
					errors.push(`allowlist: HLSL include not found: ${name}`);
					continue;
				}
				items.push({ name, file, line: 1 });
			}
		} else if (page.kind === 'shader-identifiers') {
			for (const name of page.identifiers) {
				const loc = api.hlsl.identifiers[name];
				if (!loc) {
					errors.push(`allowlist: shader identifier not found: ${name}`);
					continue;
				}
				items.push({ name, ...loc });
			}
		}
		const id = `page.${page.slug}`;
		for (const lang of langs) {
			if (scaffold) writeScaffold(lang, id, '', '', items.map((i) => ({ id: i.name })));
			const notes = readNotes(lang, id);
			usedNotes.add(`${lang}/${id}.md`);
			if (!notes) warnings.push(`notes missing: ${lang}/${id}.md`);
			else
				for (const key of notes.members.keys())
					if (!items.some((i) => i.name === key))
						errors.push(`notes: ${lang}/${id}.md describes an item that does not exist: ${key}`);
			for (const i of items) if (!notes?.members.get(i.name)) warnings.push(`undocumented: ${lang} ${id} :: ${i.name}`);
			pages.push({ lang, rel: `${category.id}/${page.slug}.md`, content: renderHlslPage(lang, page, notes, items) });
		}
	}
}

// 許可リストに無い型の説明文は、型が外れた後に残った古いものなので失敗にする。
for (const lang of langs) {
	const dir = path.join(notesDir, lang);
	if (!fs.existsSync(dir)) continue;
	for (const f of fs.readdirSync(dir))
		if (f.endsWith('.md') && !usedNotes.has(`${lang}/${f}`))
			errors.push(`notes: ${lang}/${f} is not used by the allowlist (stale?)`);
}

function firstSentence(s) {
	if (!s) return '';
	const m = /^[^。\n]*。?/.exec(s.trim());
	return (m ? m[0] : s).trim();
}

const undocumented = warnings.filter((w) => w.startsWith('undocumented')).length;
for (const w of warnings.filter((w) => !w.startsWith('undocumented'))) console.warn(`warning: ${w}`);
if (undocumented) {
	if (verbose) for (const w of warnings.filter((w) => w.startsWith('undocumented'))) console.warn(`warning: ${w}`);
	console.warn(`warning: ${undocumented} members have no description`);
}
if (strict && warnings.length) errors.push(...warnings.map((w) => `strict: ${w}`));
if (errors.length) {
	for (const e of errors) console.error(`error: ${e}`);
	console.error(`${errors.length} error(s); no pages were written.`);
	process.exit(1);
}

if (dryRun) {
	console.log(`dry run: ${pages.length} pages checked, nothing written.`);
	process.exit(0);
}

// 前回の生成物を消してから書く（手書きのページは消さない）。
for (const lang of langs) {
	const base = path.join(root, 'src/content/docs', lang, 'omni/reference');
	if (!fs.existsSync(base)) continue;
	for (const file of walk(base))
		if (file.endsWith('.md') && fs.readFileSync(file, 'utf8').includes(GENERATED_MARKER)) fs.rmSync(file);
}
for (const p of pages) {
	const file = path.join(root, 'src/content/docs', p.lang, 'omni/reference', p.rel);
	fs.mkdirSync(path.dirname(file), { recursive: true });
	fs.writeFileSync(file, p.content);
}
console.log(`${pages.length} pages written (${pages.length / langs.length} per language).`);

function* walk(dir) {
	for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
		const p = path.join(dir, e.name);
		if (e.isDirectory()) yield* walk(p);
		else yield p;
	}
}
