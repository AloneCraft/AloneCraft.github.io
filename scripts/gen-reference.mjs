// Omni のリファレンスのページを生成する。
//   入力: src/data/api/omni.json（tools/ApiExtract が Omni のソースから作る）
//         reference/omni/allowlist.yaml（載せる型）
//         reference/omni/notes/<lang>/<id>.md（手書きの説明）
//   出力: src/content/docs/<lang>/omni/reference/<category>/<slug>.md
//
// 古いページを黙って残さないため、許可リストや説明文がソースと合わないときは失敗する（SPEC.md 8 章）。
//   node scripts/gen-reference.mjs            生成する。説明の無いメンバーは警告
//   node scripts/gen-reference.mjs --strict   説明の無いメンバーも失敗にする
//   node scripts/gen-reference.mjs --scaffold 説明文の無い型に、下書き入りの雛形を作る
//   node scripts/gen-reference.mjs --dry-run  検査だけ行い、ページを書かない
//   node scripts/gen-reference.mjs --verbose  説明の無いメンバーを 1 つずつ表示する
