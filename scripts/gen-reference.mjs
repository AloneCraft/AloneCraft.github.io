const allowlist = parseYaml(fs.readFileSync(path.join(root, 'reference/omni/allowlist.yaml'), 'utf8'));
const notesDir = path.join(root, 'reference/omni/notes');

const errors = [];
const warnings = [];
const typesByName = new Map(api.types.map((t) => [t.fullName, t]));

